/**
 * RC27.14: the Halaqati motion identity, drawn from the official logo: an open book whose pages carry olive leaves,
 * with an olive branch rising from the spine. The four Lottie files live in res/raw and are generated by
 * docs/motion/generate.py from docs/motion/mark.json (the traced logo).
 *
 * Colors come from the active theme, so the user's chosen primary/accent and dark mode apply to the animations too.
 * Under "الحركة: مخففة" nothing plays; a still frame is shown instead (see [LocalReducedMotion]).
 */
enum class HalaqatiAnimation(@RawRes val res: Int, val loop: Boolean, val restProgress: Float) {
    Splash(R.raw.halaqati_splash, loop = false, restProgress = 1f),
    Loading(R.raw.halaqati_loading, loop = true, restProgress = 0.35f),
    Success(R.raw.halaqati_success, loop = false, restProgress = 1f),
    Empty(R.raw.halaqati_empty, loop = true, restProgress = 0.42f),
    EmptyPeople(R.raw.halaqati_empty_people, loop = true, restProgress = 0.25f),
    EmptyBell(R.raw.halaqati_empty_bell, loop = true, restProgress = 0f),
    EmptySearch(R.raw.halaqati_empty_search, loop = true, restProgress = 0.1f),
    EmptyDoc(R.raw.halaqati_empty_doc, loop = true, restProgress = 0.6f),
    /** Slow rotating Rub el Hizb pattern around the halaqa ring. Meant to sit behind content at low alpha. */
    Ambient(R.raw.halaqati_ambient, loop = true, restProgress = 0f),
    RoleAdmin(R.raw.halaqati_role_admin, loop = true, restProgress = 0.1f),
    RoleSupervisor(R.raw.halaqati_role_supervisor, loop = true, restProgress = 0.35f),
    RoleTeacher(R.raw.halaqati_role_teacher, loop = true, restProgress = 0.1f),
    RoleStudent(R.raw.halaqati_role_student, loop = true, restProgress = 0.35f),
    RoleGuardian(R.raw.halaqati_role_guardian, loop = true, restProgress = 0.1f),
    Milestone(R.raw.halaqati_milestone, loop = false, restProgress = 1f),
    Sync(R.raw.halaqati_sync, loop = true, restProgress = 0f),
    /** Cup with a star: rankings, competition and achievements. */
    Trophy(R.raw.halaqati_trophy, loop = true, restProgress = 0.4f),
    /** Calm cloud with a slash: no connection. */
    Offline(R.raw.halaqati_offline, loop = true, restProgress = 0.5f),
    /** Rub el Hizb star drawing itself inside the wreath: shown once after a fresh sign-in. */
    Welcome(R.raw.halaqati_welcome, loop = false, restProgress = 1f),
}

/** The three sizes of reward: a quick save, a finished task, and a real milestone. */
enum class HalaqatiMoment { Saved, Success, Milestone, Welcome }

/** Anywhere in the app can ask for a moment; [HalaqatiSuccessHost] (mounted once in MainActivity) shows it. */
object HalaqatiMotionEvents {
    private val flow = MutableSharedFlow<HalaqatiMoment>(extraBufferCapacity = 1, onBufferOverflow = BufferOverflow.DROP_OLDEST)
    val moments: SharedFlow<HalaqatiMoment> = flow.asSharedFlow()

    /** A small sprout at the bottom of the screen: frequent saves (a recitation, a plan). */
    fun saved() {
        flow.tryEmit(HalaqatiMoment.Saved)
    }

    /** The centered success card: a finished task (session closed, account approved). */
    fun celebrate() {
        flow.tryEmit(HalaqatiMoment.Success)
    }

    /** The big one: star, wreath and ribbon. Certificates and completed goals. */
    fun milestone() {
        flow.tryEmit(HalaqatiMoment.Milestone)
    }

    /** Shown once after a fresh sign-in. */
    fun welcome() {
        flow.tryEmit(HalaqatiMoment.Welcome)
    }
}

@Composable
fun HalaqatiMotion(
    animation: HalaqatiAnimation,
    modifier: Modifier = Modifier,
    finishAt: Float = 1f,
    onFinished: () -> Unit = {},
    /** True when drawn on a colored band (hero, login header): the green turns light and the gold turns soft gold. */
    onBand: Boolean = false,
) {
    val reduced = LocalReducedMotion.current
    val composition by rememberLottieComposition(LottieCompositionSpec.RawRes(animation.res))
    val progress by animateLottieCompositionAsState(
        composition = composition,
        iterations = if (animation.loop) LottieConstants.IterateForever else 1,
        isPlaying = !reduced,
    )
    val scheme = MaterialTheme.colorScheme
    val primary = if (onBand) scheme.onPrimary.toArgb() else scheme.primary.toArgb()
    val accent = if (onBand) 0xFFEBC66F.toInt() else scheme.tertiary.toArgb()
    val onPrimary = if (onBand) scheme.primary.toArgb() else scheme.onPrimary.toArgb()
    val dynamicProperties = rememberLottieDynamicProperties(
        rememberLottieDynamicProperty(LottieProperty.COLOR, primary, "**", "Primary", "**"),
        rememberLottieDynamicProperty(LottieProperty.STROKE_COLOR, primary, "**", "Primary", "**"),
        rememberLottieDynamicProperty(LottieProperty.COLOR, accent, "**", "Accent", "**"),
        rememberLottieDynamicProperty(LottieProperty.STROKE_COLOR, accent, "**", "Accent", "**"),
        rememberLottieDynamicProperty(LottieProperty.STROKE_COLOR, onPrimary, "**", "OnPrimary", "**"),
    )
    // Reading [progress] directly here would recompose this function on every frame; derivedStateOf only changes once.
    val reached by remember(animation, finishAt, reduced) {
        derivedStateOf { composition != null && !animation.loop && (reduced || progress >= finishAt) }
    }
    LaunchedEffect(reached) { if (reached) onFinished() }
    LottieAnimation(
        composition = composition,
        progress = { if (reduced) animation.restProgress else progress },
        modifier = modifier,
        dynamicProperties = dynamicProperties,
    )
}

/** Replaces the default spinner for block-level loading (not for the 18-20dp spinners inside buttons). */
@Composable
fun HalaqatiLoader(modifier: Modifier = Modifier, size: Dp = 64.dp) {
    HalaqatiMotion(
        animation = HalaqatiAnimation.Loading,
        modifier = modifier.size(size).semantics { contentDescription = "جارٍ التحميل" },
    )
}

/** The animated art for an account type: a mosque (admin), a magnifier over the book (supervisor), the Quran on its rehal
 * (teacher), a sprout from the book (student) and a heart (guardian). Enters with a soft spring. */
@Composable
fun HalaqatiRoleArt(
    role: UserRole,
    modifier: Modifier = Modifier,
    size: Dp = 72.dp,
    onBand: Boolean = false,
) {
    val reduced = LocalReducedMotion.current
    val animation = when (role) {
        UserRole.ADMIN -> HalaqatiAnimation.RoleAdmin
        UserRole.SUPERVISOR -> HalaqatiAnimation.RoleSupervisor
        UserRole.STUDENT -> HalaqatiAnimation.RoleStudent
        UserRole.GUARDIAN -> HalaqatiAnimation.RoleGuardian
        else -> HalaqatiAnimation.RoleTeacher
    }
    val pop = remember(role) { Animatable(if (reduced) 1f else 0.72f) }
    LaunchedEffect(role, reduced) {
        if (!reduced) pop.animateTo(1f, spring(dampingRatio = 0.55f, stiffness = 260f))
    }
    HalaqatiMotion(
        animation = animation,
        modifier = modifier
            .size(size)
            .graphicsLayer {
                scaleX = pop.value
                scaleY = pop.value
            },
        onBand = onBand,
    )
}

/** The slow Eastern pattern (Rub el Hizb star inside the halaqa ring). Decorative: keep it behind content. */
