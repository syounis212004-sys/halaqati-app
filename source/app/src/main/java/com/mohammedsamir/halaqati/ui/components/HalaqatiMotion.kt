}

/**
 * In-app splash shown once per cold start, over the app, so data keeps loading underneath. Tap to skip.
 * The system splash (Android 12+) cannot play Lottie, so this takes over right after it with the same background.
 */
@Composable
fun HalaqatiLaunchSplash(visible: Boolean, onDone: () -> Unit) {
    val reduced = LocalReducedMotion.current
    LaunchedEffect(reduced, visible) { if (reduced && visible) onDone() }
    // Fail-safe: if the animation can never finish (file failed to load), the app must not stay covered.
    LaunchedEffect(visible) {
        if (visible) {
            delay(3200L)
            onDone()
        }
    }
    AnimatedVisibility(
        visible = visible && !reduced,
        enter = fadeIn(tween(0)),
        exit = fadeOut(tween(220)),
    ) {
        Box(
            modifier = Modifier
                .fillMaxSize()
                .background(MaterialTheme.colorScheme.background)
                .semantics { contentDescription = "حلقاتي" }
                .clickable(interactionSource = remember { MutableInteractionSource() }, indication = null) { onDone() },
            contentAlignment = Alignment.Center,
        ) {
            HalaqatiMotion(
                animation = HalaqatiAnimation.Splash,
                modifier = Modifier.size(260.dp),
                finishAt = 0.84f,
                onFinished = onDone,
            )
            // RC27.20: the credits sit under the logo on the first screen the person sees.
            Column(
                Modifier.align(Alignment.BottomCenter).navigationBarsPadding().padding(bottom = 40.dp),
                horizontalAlignment = Alignment.CenterHorizontally,
            ) {
                Text("صُنع بأيدٍ شرقية", style = MaterialTheme.typography.titleSmall, fontWeight = FontWeight.Bold, color = com.mohammedsamir.halaqati.ui.theme.textAccent("primary"))
                Text("Designed by : Dr. Mohammed Samir Abu Younis", style = MaterialTheme.typography.labelSmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
            }
        }
    }
}

/** Short moments over the current screen (see [HalaqatiMoment]). They never block touches. */
@Composable
fun HalaqatiSuccessHost() {
    val reduced = LocalReducedMotion.current
    var token by remember { mutableIntStateOf(0) }
    var visible by remember { mutableStateOf(false) }
    var moment by remember { mutableStateOf(HalaqatiMoment.Success) }
    LaunchedEffect(Unit) {
        HalaqatiMotionEvents.moments.collect {
            moment = it
            token += 1
            visible = true
        }
    }
    LaunchedEffect(token) {
        if (token > 0) {
            val full = when (moment) {
                HalaqatiMoment.Saved -> 1300L
                HalaqatiMoment.Success -> 1700L
                HalaqatiMoment.Milestone -> 2800L
                HalaqatiMoment.Welcome -> 2600L
            }
            delay(if (reduced) 900L else full)
            visible = false
        }
    }
    AnimatedVisibility(
        visible = visible,
        enter = fadeIn(tween(motionMillis(120))),
        exit = fadeOut(tween(motionMillis(250))),
    ) {
        val saved = moment == HalaqatiMoment.Saved
        val welcome = moment == HalaqatiMoment.Welcome
        // RC27.20: the welcome is a slim toast at the top (art + one line), never a card over the middle of the page.
        Box(
            when {
                saved -> Modifier.fillMaxSize().navigationBarsPadding().padding(bottom = 84.dp)
                welcome -> Modifier.fillMaxSize().statusBarsPadding().padding(top = 64.dp)
                else -> Modifier.fillMaxSize()
            },
            contentAlignment = when {
                saved -> Alignment.BottomCenter
                welcome -> Alignment.TopCenter
                else -> Alignment.Center
            },
        ) {
            // Not a Material3 Surface: Surface consumes pointer events, and this card must never block touches.
            val shape = RoundedCornerShape(if (saved) 20.dp else if (welcome) 28.dp else 24.dp)
            Box(
                Modifier
                    .shadow(if (saved || welcome) 4.dp else 8.dp, shape)
                    .clip(shape)
                    .background(MaterialTheme.colorScheme.surface),
            ) {
                key(token) {
                    when (moment) {
                        HalaqatiMoment.Saved -> HalaqatiMotion(HalaqatiAnimation.Success, Modifier.padding(6.dp).size(84.dp))
                        HalaqatiMoment.Success -> HalaqatiMotion(HalaqatiAnimation.Success, Modifier.padding(8.dp).size(196.dp))
                        HalaqatiMoment.Milestone -> HalaqatiMotion(HalaqatiAnimation.Milestone, Modifier.padding(8.dp).size(280.dp))
                        HalaqatiMoment.Welcome -> Row(
                            Modifier.padding(start = 6.dp, end = 18.dp, top = 4.dp, bottom = 4.dp),
                            verticalAlignment = Alignment.CenterVertically,
                        ) {
                            HalaqatiMotion(HalaqatiAnimation.Welcome, Modifier.size(52.dp))
                            Text(
                                "أهلًا بك في حلقاتي",
                                style = MaterialTheme.typography.titleSmall,
                                fontWeight = FontWeight.Bold,
                                color = com.mohammedsamir.halaqati.ui.theme.textAccent("primary"),
                            )
                        }
                    }
                }
            }
        }
    }
}
