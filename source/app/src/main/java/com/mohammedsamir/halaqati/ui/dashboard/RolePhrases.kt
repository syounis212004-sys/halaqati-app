    /** role is the lower-case role name: admin, supervisor, teacher, guardian, observer. */
    fun forRole(role: String, daySeed: Long): RolePhrase {
        val list = when (role.lowercase()) {
            "admin" -> admin
            "supervisor" -> supervisor
            "guardian" -> guardian
            "observer" -> donor
            else -> teacher
        }
        return list[Math.floorMod(daySeed, list.size.toLong()).toInt()]
    }

    /** A time-based greeting: morning, afternoon or evening. */
    fun greeting(hour: Int): String = when (hour) {
        in 4..11 -> "صباح الخير"
        in 12..16 -> "نهارك مبارك"
        in 17..20 -> "مساء الخير"
        else -> "ليلة مباركة"
    }
